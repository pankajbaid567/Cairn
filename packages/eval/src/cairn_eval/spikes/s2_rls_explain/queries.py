"""SQL for the S2 variants (Phase 0 design §14, step 4; free-tier retarget design §5).

Every value is generated by the harness, so literals are inlined with ``psycopg.sql.Literal``
and nothing here takes user input.

Lexical search is native full-text search (FT-05): the stored generated column ``body_tsv``
(``to_tsvector('simple', body)``) with the GIN index ``chunks_fts_idx``, queried with
``websearch_to_tsquery('simple', …)`` and ranked with ``ts_rank_cd``. The query terms are
joined with `` or `` (``websearch_to_tsquery`` ANDs bare words) and reach the statement as one
SQL string literal. Under ``simple`` an S1 topic token ``t3_5`` becomes the phrase
``'t3' <-> '5'``, which matches exactly the bodies that hold the token (Verify FV12).
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Final

from psycopg import sql

from cairn_eval.spikes.s2_rls_explain.config import (
    PRINCIPAL_SETTING,
    RESULT_LIMIT,
    RRF_DEPTH,
    RRF_K,
    SPIKE_SCHEMA,
    SPIKE_TABLE,
)

VARIANTS: Final = (
    "fts",
    "fts_explicit_acl",
    "hnsw",
    "hnsw_explicit_acl",
    "hybrid_rrf",
    "hybrid_rrf_explicit_acl",
)
"""Every query shape with and without the explicit ACL predicate (Requirement 3.2)."""
EXPLICIT_SUFFIX: Final = "_explicit_acl"
TS_CONFIG: Final = "simple"
"""Text-search configuration of the generated column and of every lexical query."""
TERM_SEPARATOR: Final = " or "
"""``websearch_to_tsquery`` reads ``or`` as OR; bare words would be ANDed."""
TSV_COLUMN: Final = "body_tsv"
TABLE: Final = sql.Identifier(SPIKE_SCHEMA, SPIKE_TABLE)
EXPLAIN: Final = sql.SQL("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) ")


def is_explicit(variant: str) -> bool:
    """True for the variants that add the ACL predicate to the query text (the L2 shape)."""
    return variant.endswith(EXPLICIT_SUFFIX)


def shape_of(variant: str) -> str:
    """``fts``, ``hnsw`` or ``hybrid_rrf``."""
    return variant.removesuffix(EXPLICIT_SUFFIX)


def lexical_text(terms: Sequence[str]) -> str:
    """The text handed to ``websearch_to_tsquery``: the terms joined with `` or ``."""
    return TERM_SEPARATOR.join(terms)


def group_literal(groups: Sequence[int]) -> sql.Literal:
    """A Postgres array literal such as ``'{1000,1001}'``; ``'{}'`` for no groups."""
    return sql.Literal("{" + ",".join(str(int(g)) for g in groups) + "}")


def vector_literal(vector: Sequence[float]) -> sql.Literal:
    """A pgvector text literal such as ``'[0.1,0.2]'``."""
    return sql.Literal("[" + ",".join(repr(float(x)) for x in vector) + "]")


def _acl_predicate(groups: Sequence[int]) -> sql.Composable:
    return sql.SQL("acl && {}::int[]").format(group_literal(groups))


def _where(parts: list[sql.Composable]) -> sql.Composable:
    if not parts:
        return sql.SQL("")
    return sql.SQL(" WHERE ") + sql.SQL(" AND ").join(parts)


def fts_query(terms: Sequence[str], groups: Sequence[int] | None, limit: int) -> sql.Composed:
    """Top ``limit`` rows by ``ts_rank_cd``; ``groups`` adds the explicit ACL predicate.

    ``SELECT id, ts_rank_cd(body_tsv, q) AS score FROM s2.chunks,
    websearch_to_tsquery('simple', '<terms joined with or>') AS q
    WHERE body_tsv @@ q [AND acl && '{…}'::int[]] ORDER BY score DESC, id LIMIT <limit>``
    """
    parts: list[sql.Composable] = [sql.SQL("{col} @@ q").format(col=sql.Identifier(TSV_COLUMN))]
    if groups is not None:
        parts.append(_acl_predicate(groups))
    return sql.SQL(
        "SELECT id, ts_rank_cd({col}, q) AS score "
        "FROM {table}, websearch_to_tsquery({config}, {terms}) AS q{where} "
        "ORDER BY score DESC, id LIMIT {limit}"
    ).format(
        col=sql.Identifier(TSV_COLUMN),
        table=TABLE,
        config=sql.Literal(TS_CONFIG),
        terms=sql.Literal(lexical_text(terms)),
        where=_where(parts),
        limit=sql.Literal(limit),
    )


def hnsw_query(vector: Sequence[float], groups: Sequence[int] | None, limit: int) -> sql.Composed:
    """Top ``limit`` rows by cosine distance; ``groups`` adds the explicit ACL predicate."""
    parts: list[sql.Composable] = [] if groups is None else [_acl_predicate(groups)]
    return sql.SQL(
        "SELECT id FROM {table}{where} ORDER BY embedding <=> {vec}::vector LIMIT {limit}"
    ).format(table=TABLE, where=_where(parts), vec=vector_literal(vector), limit=sql.Literal(limit))


def hybrid_query(
    terms: Sequence[str],
    vector: Sequence[float],
    groups: Sequence[int] | None,
    limit: int,
) -> sql.Composed:
    """Reciprocal rank fusion of the two searches, ``RRF_DEPTH`` rows from each side. The
    lexical side is the ``fts`` statement."""
    vec_parts: list[sql.Composable] = [] if groups is None else [_acl_predicate(groups)]
    return sql.SQL(
        "WITH lex AS (SELECT id, row_number() OVER (ORDER BY score DESC, id) AS r FROM ("
        "{lexical}) t), "
        "vec AS (SELECT id, row_number() OVER (ORDER BY dist) AS r FROM ("
        "SELECT id, embedding <=> {vec}::vector AS dist FROM {table}{vec_where} "
        "ORDER BY embedding <=> {vec}::vector LIMIT {depth}) t) "
        "SELECT coalesce(lex.id, vec.id) AS id, "
        "coalesce(1.0 / ({k} + lex.r), 0) + coalesce(1.0 / ({k} + vec.r), 0) AS rrf "
        "FROM lex FULL OUTER JOIN vec ON lex.id = vec.id ORDER BY rrf DESC LIMIT {limit}"
    ).format(
        lexical=fts_query(terms, groups, RRF_DEPTH),
        table=TABLE,
        vec_where=_where(vec_parts),
        vec=vector_literal(vector),
        depth=sql.Literal(RRF_DEPTH),
        k=sql.Literal(RRF_K),
        limit=sql.Literal(limit),
    )


def build_query(
    variant: str,
    *,
    terms: Sequence[str],
    vector: Sequence[float],
    groups: Sequence[int],
    limit: int = RESULT_LIMIT,
) -> sql.Composed:
    """The statement for ``variant``. ``groups`` is used only by the explicit variants."""
    if variant not in VARIANTS:
        raise ValueError(f"unknown S2 variant {variant!r}")
    explicit = groups if is_explicit(variant) else None
    shape = shape_of(variant)
    if shape == "fts":
        return fts_query(terms, explicit, limit)
    if shape == "hnsw":
        return hnsw_query(vector, explicit, limit)
    return hybrid_query(terms, vector, explicit, limit)


def set_local(name: str, value: str | int) -> sql.Composed:
    """``SET LOCAL <name> = <value>`` for a harness-controlled setting name."""
    return sql.SQL("SET LOCAL {name} = {value}").format(
        name=sql.SQL(name), value=sql.Literal(value)
    )


def set_principal(groups: Sequence[int]) -> sql.Composed:
    """``SET LOCAL cairn.principal_groups = '{...}'``."""
    return sql.SQL("SET LOCAL {name} = {value}").format(
        name=sql.SQL(PRINCIPAL_SETTING), value=group_literal(groups)
    )
